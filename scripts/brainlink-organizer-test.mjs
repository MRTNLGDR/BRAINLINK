import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(process.argv[2] ?? path.join(process.cwd(), '.brainlink-workspace', 'AFFiNE'));
const read = relative => fs.readFileSync(path.join(root, ...relative.split('/')), 'utf8');
const checks = [];
const check = (name, condition) => checks.push({ name, ok: Boolean(condition) });
const organizer = read('packages/frontend/core/src/brainlink/brainlink-organizer.tsx');
const app = read('packages/frontend/core/src/brainlink/app.tsx');
const catalog = read('packages/frontend/core/src/brainlink/catalog.ts');
const sidebar = read('packages/frontend/core/src/components/root-app-sidebar/index.tsx');
const brain = read('packages/frontend/core/src/desktop/pages/workspace/chat/brainlink-local-ai.tsx');
check('Total organization domains are routed', ['organization', 'life', 'ideas', 'company', 'budget', 'people', 'brains'].every(slug => catalog.includes(`slug: '${slug}'`)));
check('Organizer uses real workspace documents', organizer.includes('WorkspaceService') && organizer.includes('DocDisplayMetaService') && organizer.includes("workbench.open('/' + entity.documentId)"));
check('Organizer persists real local-first records', organizer.includes('brainlink:organizer:v1') && organizer.includes('localStorage.setItem(STORAGE_KEY'));
check('Brain observability exposes actual work and compliance', organizer.includes('Actually doing') && organizer.includes('Documentation compliance') && organizer.includes('lastHeartbeat') && organizer.includes('CHECKPOINT'));
check('Existing Brainlink state remains execution authority', organizer.includes('BrainlinkState') && organizer.includes('commit(') && app.includes('<BrainlinkOrganizer'));
check('Brain is the visible intelligence identity', sidebar.includes('>Brain</span>') && brain.includes('<ViewTitle title="Brain" />') && brain.includes('You are Brain, the local intelligence'));
for (const result of checks) console.log(`${result.ok ? 'PASS' : 'FAIL'}  ${result.name}`);
const passed = checks.filter(result => result.ok).length;
console.log(`\n${passed}/${checks.length} Brainlink organization checks passed.`);
if (passed !== checks.length) process.exit(1);
